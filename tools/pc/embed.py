#!/usr/bin/env python3
"""Puts tools/pc/hamos.html into the firmware as src/core/WebPage.h.

The Cardputer serves the same control page over WiFi. It is stored gzip
compressed (browsers unpack it) and marked with a "hamos-device" meta tag so
the page talks to the device's /api instead of USB.

Run it again after changing hamos.html:  python3 tools/pc/embed.py
"""
import gzip
import os

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "hamos.html")
out = os.path.join(here, "..", "..", "src", "core", "WebPage.h")

html = open(src, encoding="utf-8").read()
marker = '<meta charset="utf-8">'
assert marker in html, "hamos.html must contain " + marker
html = html.replace(marker, marker + '<meta name="hamos-device" content="1">', 1)
data = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)

lines = []
for i in range(0, len(data), 20):
    lines.append("    " + ",".join("0x%02x" % b for b in data[i:i + 20]) + ",")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/pc/embed.py from tools/pc/hamos.html - do not edit.\n")
    f.write("#pragma once\n#include <cstddef>\n#include <cstdint>\n\nnamespace web {\n")
    f.write("static const uint8_t kPageGz[] = {\n" + "\n".join(lines) + "\n};\n")
    f.write("static const size_t kPageGzLen = sizeof(kPageGz);\n}  // namespace web\n")
print("%s: %d bytes of HTML -> %d bytes gzip" % (os.path.relpath(out), len(html.encode()), len(data)))
