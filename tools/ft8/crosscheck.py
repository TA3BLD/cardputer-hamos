"""Cross-checks the HamOS FT8 code (src/lib/Ft8.h, Ft8Decoder.h) against the
WSJT-X port in the Python package "ft8lib".

  pip install ft8lib numpy
  g++ -std=c++17 -O2 -I src test/host/ft8_tool.cpp -o /tmp/ft8_tool
  python tools/ft8/crosscheck.py /tmp/ft8_tool

1. Message packing: the 77 bits and 79 tones must be identical for standard messages.
2. Transmit: ft8lib must decode the audio HamOS generates.
3. Receive: HamOS must decode audio generated by ft8lib, with noise, time and
   frequency offsets and several signals at once. Prints the decode rate per SNR.
"""
import os
import random
import subprocess
import sys
import tempfile

import numpy as np
import ft8lib

# ft8lib's chkcall() differs from WSJT-X's lib/chkcall.f90 in one place: for a
# call with digits in both the 2nd and 3rd position (A61AA, S57DX, E73X) the
# Fortran takes the 3rd as the area digit ("if" twice), the Python port the 2nd
# ("elif") and then rejects the call. WSJT-X sends such calls as standard
# messages, so the reference is corrected here to match WSJT-X.
from ft8lib import pack as _pack


def _chkcall_wsjtx(w):
    w = w.strip().upper()
    bc = w[:6]
    n1 = len(w)
    if n1 > 11 or any(ch in w for ch in ".+-?"):
        return bc, False
    if n1 > 6 and "/" not in w:
        return bc, False
    i0 = w.find("/") + 1
    if i0 and max(i0 - 1, n1 - i0) > 6:
        return bc, False
    if 2 <= i0 <= n1 - 1:
        bc = w[i0:] if i0 - 1 <= n1 - i0 else w[: i0 - 1]
    if len(bc) > 6 or not (bc[:1].isalpha() or bc[1:2].isalpha()):
        return bc, False
    if bc.startswith("Q") and bc[:5] != "QU1RK":
        return bc, False
    i1 = 0
    if len(bc) >= 2 and bc[1].isdigit():
        i1 = 2
    if len(bc) >= 3 and bc[2].isdigit():
        i1 = 3
    if i1 == 0 or i1 == len(bc):
        return bc, False
    sfx = bc[i1:]
    return bc, sfx.isalpha() and 1 <= len(sfx) <= 3


_pack.chkcall = _chkcall_wsjtx

tool = sys.argv[1]
tmp = tempfile.mkdtemp()
random.seed(7)
rng = np.random.default_rng(7)
letters, digits = "ABCDEFGHIJKLMNOPQRSTUVWXYZ", "0123456789"


def rcall():
    first = letters.replace("Q", "")          # no callsign starts with Q
    pre = random.choice([random.choice(first), random.choice(first) + random.choice(letters),
                         random.choice(digits) + random.choice(letters), random.choice(first) + random.choice(digits)])
    return pre + random.choice(digits) + "".join(random.choice(letters) for _ in range(random.randint(1, 3)))


def rgrid():
    return random.choice("ABCDEFGHIJKLMNOPQR") + random.choice("ABCDEFGHIJKLMNOPQR") + random.choice(digits) + random.choice(digits)


def rmessage():
    a, b = rcall(), rcall()
    return random.choice(["%s %s %s" % (a, b, rgrid()), "%s %s %+03d" % (a, b, random.randint(-24, 30)),
                          "%s %s R%+03d" % (a, b, random.randint(-24, 30)), "CQ %s %s" % (b, rgrid()),
                          "%s %s RR73" % (a, b), "%s %s 73" % (a, b), "%s %s RRR" % (a, b),
                          "CQ DX %s %s" % (b, rgrid()), "%s %s R %s" % (a, b, rgrid())])


def run(*args):
    return subprocess.run([tool] + list(args), capture_output=True, text=True, check=True).stdout


failures = 0

# ---- 1. packing ----
fixed = ["CQ TA3BLD KM38", "CQ DX JA1ABC PM95", "CQ POTA K4ABC EM73", "CQ 123 G4XYZ IO91", "TA1ABC TA3BLD -12",
         "TA1ABC TA3BLD R-12", "TA1ABC TA3BLD RR73", "TA1ABC TA3BLD 73", "TA1ABC TA3BLD RRR", "9A1A 4X1AB JN75",
         "QRZ TA3BLD KM38", "TNX BOB 73 GL", "HELLO WORLD", "A", "73", "VK2DX ZS6ABC -30", "G4XYZ PY2XYZ -31",
         "123456789ABCDEF012", "TA1ABC TA3BLD"]
messages = fixed + [rmessage() for _ in range(1500)]
same = refused = 0
for m in messages:
    out = (run("payload", m).split("\n") + ["", "", ""])[:3]
    ref = ft8lib.pack77(m)
    refbits = "".join(str(int(x)) for x in ref)
    reftones = "".join(str(int(x)) for x in ft8lib.ft8_tones_from_bits(ref))
    reftext = ft8lib.unpack77(ref)[0].strip()
    if out[0] == "ERROR" and refbits.endswith("000000") and len(m) > 13:
        refused += 1                            # HamOS will not cut a message short
    elif out[0] != refbits or out[1] != reftones or out[2] != reftext:
        failures += 1
        print("PACK DIFF %r\n  mine %s %r\n  ref  %s %r" % (m, out[0], out[2], refbits, reftext))
    else:
        same += 1
    # and the other direction: HamOS reads the reference bits
    if run("unpack", refbits).strip() != reftext:
        failures += 1
        print("UNPACK DIFF %r: %r" % (m, run("unpack", refbits).strip()))
print("1. packing: %d of %d messages identical (bits, tones, text); %d too long for free text, refused" %
      (same, len(messages), refused))


def write_raw(path, audio):
    np.clip(audio, -32767, 32767).astype("<i2").tofile(path)


def resample_12k_to_8k(x):
    # exact 3:2 decimation through the FFT
    n = len(x) - len(x) % 3
    spec = np.fft.rfft(x[:n])
    m = n * 2 // 3
    out = np.fft.irfft(spec[: m // 2 + 1], m) * (m / n)
    return out


def noise_for(snr_db, amplitude, fs, n):
    # SNR referred to 2500 Hz, as WSJT-X reports it
    signal_power = amplitude ** 2 / 2
    sigma = np.sqrt(signal_power / 10 ** (snr_db / 10) * (fs / 2) / 2500)
    return rng.normal(0, sigma, n)


# ---- 2. HamOS transmit -> ft8lib receive ----
tx_msgs = [("CQ TA3BLD KM38", 1500.0), ("TA1ABC DL1ABC -12", 812.5), ("VK2DX TA3BLD R+05", 2203.0)]
args = []
for m, f in tx_msgs:
    args += [str(f), m]
path = os.path.join(tmp, "tx.raw")
run("encode", path, "12000", *args)
audio = np.fromfile(path, dtype="<i2").astype(float)
audio += noise_for(-5, 4000, 12000, len(audio))
found = {d.message.strip(): d for d in ft8lib.decode_ft8(audio / 32768.0)}
for m, f in tx_msgs:
    d = found.get(m)
    ok = d is not None and abs(d.freq - f) < 3 and abs(d.dt - 0.0) < 0.2
    print("2. ft8lib decodes HamOS audio %-22s %s" % (m, "ok (%.1f Hz, dt %.2f, %d dB)" % (d.freq, d.dt, d.snr) if d else "NOT FOUND"))
    failures += not ok

# ---- 3. ft8lib transmit -> HamOS receive ----
def scene(snrs, osr):
    """One 15 s period with several signals; returns (decoded, total)."""
    fs = 12000
    used = []
    expect = {}
    for snr in snrs:
        while True:
            f = random.uniform(300, 2800)
            if all(abs(f - u) > 60 for u in used):
                break
        used.append(f)
        msg = rmessage()
        expect[ft8lib.unpack77(ft8lib.pack77(msg))[0].strip()] = (f, random.uniform(-0.8, 0.8), snr)
    audio = np.zeros(15 * fs)
    noise = rng.normal(0, 1, 15 * fs)
    noise_sigma = 1500.0
    noise *= noise_sigma
    for (msg, (f, dt, snr)) in expect.items():
        signal_power = noise_sigma ** 2 * 2500 / (fs / 2) * 10 ** (snr / 10)      # noise power in 2500 Hz x SNR
        a = np.sqrt(2 * signal_power)
        wave = ft8lib.encode_ft8(msg, f0=f) * a
        start = int((0.5 + dt) * fs)
        lo, hi = max(0, start), min(15 * fs, start + len(wave))
        audio[lo:hi] += wave[lo - start: hi - start]
    audio += noise
    audio8 = resample_12k_to_8k(audio)
    path = os.path.join(tmp, "rx.raw")
    write_raw(path, audio8)
    lines = run("decode", path, "8000", str(osr)).strip().split("\n")
    got = {}
    for line in lines:
        if line:
            snr, dt, f, text = line.split(" ", 3)
            got[text] = (float(f), float(dt), int(snr))
    hits = 0
    for msg, (f, dt, snr) in expect.items():
        g = got.get(msg)
        if g and abs(g[0] - f) < 6.5 and abs(g[1] - dt) < 0.25:
            hits += 1
            snr_err.append(g[2] - snr)
    false = [t for t in got if t not in expect]
    return hits, len(expect), false


for osr in (2, 1):
    print("3. HamOS decodes ft8lib audio (freq osr %d):" % osr)
    snr_err = []
    total_false = 0
    for snr in (-6, -10, -13, -15, -17, -19, -21, -23):
        hits = total = 0
        for _ in range(6):
            h, t, false = scene([snr] * 5, osr)
            hits += h
            total += t
            total_false += len(false)
            for fl in false:
                print("   FALSE DECODE %r" % fl)
        print("   SNR %+3d dB: %3d%% (%d of %d)" % (snr, 100 * hits // total, hits, total))
        if snr >= -15 and hits < total * 0.9:
            failures += 1
    print("   SNR report error: mean %+.1f dB, spread %.1f dB, false decodes %d" %
          (np.mean(snr_err), np.std(snr_err), total_false))
    failures += total_false

print("FAILURES: %d" % failures)
sys.exit(1 if failures else 0)
