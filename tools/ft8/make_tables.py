"""Writes src/lib/Ft8Tables.h: the constants of the FT8 LDPC(174,91) code.

The numbers are part of the FT8 protocol (K1JT, K9AN, G4WJS: "The FT4 and FT8
Communication Protocols", QEX 2020; WSJT-X lib/ft8/ldpc_174_91_c_*.f90). This
script takes them from the "ft8lib" Python package (pip install ft8lib) and
checks that the generator and the parity-check matrix agree with each other.
"""
import random
import sys
from ft8lib import _tables as T

gen = [int(h + "0", 16) for h in T.LDPC_GENERATOR_HEX]      # 91 bits, left aligned in 96
nm = [list(row) for row in T.LDPC_NM]                       # 1-based bit numbers, 0 = unused
assert len(gen) == 83 and len(nm) == 83 and all(len(r) == 7 for r in nm)

# Every codeword [message | parity] must satisfy every parity check.
for _ in range(200):
    msg = random.getrandbits(91)
    bits = [(msg >> (90 - i)) & 1 for i in range(91)]
    for row in gen:
        bits.append(bin((row >> 5) & msg).count("1") & 1)
    for check in nm:
        assert sum(bits[n - 1] for n in check if n) % 2 == 0
# Each bit takes part in exactly three checks.
uses = [0] * 174
for check in nm:
    for n in check:
        if n:
            uses[n - 1] += 1
assert all(u == 3 for u in uses)

out = ["// Generated by tools/ft8/make_tables.py - do not edit.",
       "// Constants of the FT8 LDPC(174,91) code, as published with the FT8 protocol.",
       "#pragma once", "#include <cstdint>", "", "namespace ft8 {", "",
       "// Generator: parity bit j is the parity of (row j AND the 91 message bits).",
       "// Rows hold the 91 bits left-aligned in 12 bytes.",
       "static const uint8_t kGenerator[83][12] = {"]
for g in gen:
    out.append("    {" + ", ".join("0x%02x" % b for b in g.to_bytes(12, "big")) + "},")
out += ["};", "", "// Parity checks: the codeword bits (1..174) each check covers; 0 = unused.",
        "static const uint8_t kChecks[83][7] = {"]
for row in nm:
    out.append("    {" + ", ".join("%3d" % n for n in row) + "},")
out += ["};", "", "}  // namespace ft8", ""]
open(sys.argv[1], "w").write("\n".join(out))
print("tables written and verified")
